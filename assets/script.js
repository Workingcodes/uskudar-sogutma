function applyLang(lang) {
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (translations[lang] && translations[lang][key]) {
      el.textContent = translations[lang][key];
    }
  });
  document.querySelectorAll('.lang-btn').forEach(b => b.classList.toggle('active', b.dataset.lang === lang));
  localStorage.setItem('lang', lang);
  document.documentElement.lang = lang === 'tr' ? 'tr' : 'en';
}

document.addEventListener('DOMContentLoaded', () => {
  const saved = localStorage.getItem('lang') || 'tr';
  applyLang(saved);

  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.addEventListener('click', () => applyLang(btn.dataset.lang));
  });

  /* Navbar scroll */
  const navbar = document.getElementById('navbar');
  window.addEventListener('scroll', () => {
    navbar?.classList.toggle('scrolled', window.scrollY > 40);
  });

  /* Hamburger */
  const hamburger = document.getElementById('navHamburger');
  const mobileNav = document.getElementById('navMobile');
  hamburger?.addEventListener('click', () => mobileNav?.classList.toggle('open'));

  /* Scroll animations */
  const observer = new IntersectionObserver(entries => {
    entries.forEach(e => { if (e.isIntersecting) e.target.classList.add('visible'); });
  }, { threshold: 0.12 });
  document.querySelectorAll('.fade-in, .slide-left, .slide-right').forEach(el => observer.observe(el));

  /* Counter animation */
  document.querySelectorAll('.stat-num[data-target]').forEach(el => {
    const target = parseFloat(el.dataset.target);
    const isFloat = target % 1 !== 0;
    const suffix = el.dataset.suffix || '';
    let start = 0;
    const step = target / 60;
    const tick = () => {
      start = Math.min(start + step, target);
      el.textContent = (isFloat ? start.toFixed(1) : Math.floor(start)) + suffix;
      if (start < target) requestAnimationFrame(tick);
    };
    const io = new IntersectionObserver(([e]) => { if (e.isIntersecting) { tick(); io.disconnect(); } });
    io.observe(el);
  });

  /* Gallery lightbox */
  const lightbox = document.getElementById('lightbox');
  const lbImg = document.getElementById('lbImg');
  let currentIdx = 0;
  const galleryItems = document.querySelectorAll('.gallery-page-item[data-src], .gallery-item[data-src]');

  galleryItems.forEach((item, idx) => {
    item.addEventListener('click', () => {
      currentIdx = idx;
      if (lightbox && lbImg) {
        lbImg.src = item.dataset.src;
        lightbox.classList.add('open');
      }
    });
  });

  document.getElementById('lbClose')?.addEventListener('click', () => {
    lightbox?.classList.remove('open');
    if (lbImg) lbImg.src = '';
  });
  document.getElementById('lbPrev')?.addEventListener('click', () => {
    currentIdx = (currentIdx - 1 + galleryItems.length) % galleryItems.length;
    if (lbImg) lbImg.src = galleryItems[currentIdx].dataset.src;
  });
  document.getElementById('lbNext')?.addEventListener('click', () => {
    currentIdx = (currentIdx + 1) % galleryItems.length;
    if (lbImg) lbImg.src = galleryItems[currentIdx].dataset.src;
  });
  document.addEventListener('keydown', e => {
    if (!lightbox?.classList.contains('open')) return;
    if (e.key === 'Escape') { lightbox.classList.remove('open'); if (lbImg) lbImg.src = ''; }
    if (e.key === 'ArrowLeft') { currentIdx = (currentIdx - 1 + galleryItems.length) % galleryItems.length; if (lbImg) lbImg.src = galleryItems[currentIdx].dataset.src; }
    if (e.key === 'ArrowRight') { currentIdx = (currentIdx + 1) % galleryItems.length; if (lbImg) lbImg.src = galleryItems[currentIdx].dataset.src; }
  });
  lightbox?.addEventListener('click', e => {
    if (e.target === lightbox) { lightbox.classList.remove('open'); if (lbImg) lbImg.src = ''; }
  });
});
